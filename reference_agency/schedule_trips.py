"""Schedule one service day of paratransit trips with a full audit trail.

Two-stage scheduler mirroring real paratransit ops:
  1. Pooling: trips to/from hub destinations (dialysis center, adult day
     programs, medical cluster) are batched into shared runs of up to 4
     riders when requested within a 25-minute span, like real standing-order
     runs. Everything else rides solo (shared-ride pooling for non-hub trips
     is roadmap).
  2. Assignment: greedy insertion of runs onto vehicles. Every decision is
     logged with the factors that drove it and the alternatives rejected,
     with reasons. The audit trail is the product wedge.

Outputs: reference_agency/output/schedule.csv, audit_log.json, day_stats.json
"""

import json
import numpy as np
import pandas as pd
from pathlib import Path

OUT = Path(__file__).parent / "output"
trips = pd.read_csv(OUT / "trips.csv", parse_dates=["date"])
zones = pd.read_csv(OUT / "zones.csv").set_index("zone_id")

DAY = "2026-04-14"  # a representative Tuesday from the held-out window
day = trips[(trips.date == DAY) & (trips.status == "completed")].copy()
day["req_min"] = day.hour * 60 + day.req_minute
day = day.sort_values("req_min").reset_index(drop=True)

CELL_KM = 3.0
SPEED_KMH = 28.0
DWELL_MIN = 4
WINDOW_EARLY = 10
WINDOW_LATE = 20
POOL_SPAN_MIN = 30
POOL_MAX = 5
HUBS = set(zones.index[(zones.has_dialysis == 1) | (zones.has_daycenter == 1)
                       | (zones.has_medical == 1)])

def travel_min(za, zb):
    a, b = zones.loc[za], zones.loc[zb]
    km = (abs(a.gx - b.gx) + abs(a.gy - b.gy)) * CELL_KM
    return km / SPEED_KMH * 60

# ------------------------------------------------------------------ pooling
runs, used = [], set()
for t in day.itertuples():
    if t.Index in used:
        continue
    if t.dest_zone in HUBS:
        hub, direction = t.dest_zone, "inbound"
    elif t.origin_zone in HUBS:
        hub, direction = t.origin_zone, "outbound"
    else:
        hub, direction = None, None
    members = [t]
    used.add(t.Index)
    if hub is not None:
        for u in day.itertuples():
            if len(members) >= POOL_MAX:
                break
            if u.Index in used or u.req_min - t.req_min > POOL_SPAN_MIN:
                continue
            same_hub = (direction == "inbound" and u.dest_zone == hub) or \
                       (direction == "outbound" and u.origin_zone == hub)
            if same_hub:
                members.append(u)
                used.add(u.Index)
    # Route: inbound = chain of pickups then hub; outbound = hub then drop chain
    if direction == "inbound":
        stops = [m.origin_zone for m in members] + [hub]
    elif direction == "outbound":
        stops = [hub] + [m.dest_zone for m in members]
    else:
        stops = [t.origin_zone, t.dest_zone]
    leg_min = sum(travel_min(a, b) for a, b in zip(stops, stops[1:]))
    service_min = leg_min + DWELL_MIN * (len(members) + 1)
    runs.append({
        "req_min": members[0].req_min, "first_stop": stops[0], "last_stop": stops[-1],
        "members": members, "service_min": service_min,
        "wheelchair": any(m.wheelchair for m in members),
        "kind": f"{direction or 'direct'}" + (f" pool x{len(members)}" if len(members) > 1 else ""),
    })
runs.sort(key=lambda r: r["req_min"])

# --------------------------------------------------------------- assignment
class Vehicle:
    def __init__(self, vid, shift_start, shift_end, wheelchair_capable):
        self.vid, self.shift_start, self.shift_end = vid, shift_start, shift_end
        self.wheelchair_capable = wheelchair_capable
        self.free_at, self.loc = float(shift_start * 60), "Z27"
        self.drive_min = self.deadhead_min = 0.0
        self.blocks = []

FLEET = (
    [Vehicle(f"V{i:02d}", 5, 14, True) for i in range(1, 7)] +
    [Vehicle(f"V{i:02d}", 8, 17, False) for i in range(7, 13)] +
    [Vehicle(f"V{i:02d}", 10, 19, True) for i in range(13, 17)] +
    [Vehicle(f"V{i:02d}", 13, 22, True) for i in range(17, 21)]
)

# Structured reason codes for every denial/rejection, alongside the
# human-readable text. Deterministic and rule-traceable (derived directly
# from the constraint that failed, not from a model): this is the
# compliance trail, and it is never generated by SHAP or any other model
# explanation. Only codes for constraints this scheduler actually checks
# are listed here -- do not add MAX_RIDE_TIME or SERVICE_AREA until the
# scheduler enforces those constraints for real.
NO_ACCESSIBLE_CAPACITY = "NO_ACCESSIBLE_CAPACITY"
NEGOTIATION_WINDOW = "NEGOTIATION_WINDOW"
SHIFT_END = "SHIFT_END"

audit, rows = [], []
served = unserved = 0

for run in runs:
    win_open = run["req_min"] - WINDOW_EARLY
    # Standing orders (dialysis, day program) are pre-scheduled the night
    # before: the agency sets the pickup time, so the window is negotiable
    lead_purpose = run["members"][0].purpose
    if lead_purpose in ("dialysis", "dayprogram"):
        win_close = run["req_min"] + 45
    else:
        # 49 CFR 37.131(b)(2): pickup time may be negotiated up to one hour
        # from the requested time. WINDOW_LATE is the preferred window; the
        # negotiated ceiling is the legal bound.
        win_close = run["req_min"] + 60
    candidates, rejected = [], []
    for v in FLEET:
        if run["wheelchair"] and not v.wheelchair_capable:
            rejected.append({"vehicle": v.vid, "code": NO_ACCESSIBLE_CAPACITY,
                             "reason": "no wheelchair securement"})
            continue
        dead = travel_min(v.loc, run["first_stop"])
        eta = max(v.free_at + dead, win_open)
        if eta > win_close:
            rejected.append({"vehicle": v.vid, "code": NEGOTIATION_WINDOW,
                             "reason": f"cannot reach first pickup before window closes ({eta - win_close:.0f} min late)"})
            continue
        done = eta + run["service_min"]
        if done > v.shift_end * 60:
            rejected.append({"vehicle": v.vid, "code": SHIFT_END,
                             "reason": "run would extend past end of shift"})
            continue
        wait = eta - win_open
        candidates.append((dead + 0.4 * wait, dead, eta, done, v))

    lead = run["members"][0]
    if not candidates:
        unserved += len(run["members"])
        audit.append({
            "run_kind": run["kind"], "decision": "UNSERVED",
            "riders": [m.rider_id for m in run["members"]],
            "requested": f"{lead.hour:02d}:{lead.req_minute:02d}",
            "reasons_by_vehicle": rejected[:4],
        })
        continue

    candidates.sort(key=lambda c: c[0])
    cost, dead, eta, done, best = candidates[0]
    runner_up = candidates[1] if len(candidates) > 1 else None
    served += len(run["members"])

    factors = [
        f"closest available vehicle: {dead:.0f} min repositioning from {best.loc}",
        f"first pickup {eta - run['req_min']:+.0f} min vs requested, inside the "
        f"[-{WINDOW_EARLY}, +{WINDOW_LATE}] min on-time window",
    ]
    if "pool" in run["kind"]:
        factors.append(
            f"{len(run['members'])} riders batched to the same facility "
            f"(requests within {POOL_SPAN_MIN} min), one shared run instead of "
            f"{len(run['members'])} separate dispatches")
    if run["wheelchair"]:
        factors.append("wheelchair securement required; vehicle is lift-equipped")
    if runner_up and runner_up[1] - dead >= 1:
        factors.append(
            f"beat {runner_up[4].vid} which would add "
            f"{runner_up[1] - dead:.0f} more repositioning minutes")

    audit.append({
        "run_kind": run["kind"], "decision": best.vid,
        "riders": [m.rider_id for m in run["members"]],
        "purpose": lead.purpose,
        "requested": f"{lead.hour:02d}:{lead.req_minute:02d}",
        "pickup_eta": f"{int(eta // 60):02d}:{int(eta % 60):02d}",
        "route": f"{run['first_stop']} -> {run['last_stop']}",
        "factors": factors,
        "rejected": rejected[:3],
    })
    rows.append({
        "vehicle": best.vid, "kind": run["kind"], "riders": len(run["members"]),
        "purpose": lead.purpose, "start_min": round(eta, 1),
        "end_min": round(done, 1), "deadhead_min": round(dead, 1),
        "wheelchair": bool(run["wheelchair"]),
    })
    best.free_at, best.loc = done, run["last_stop"]
    best.drive_min += dead + run["service_min"]
    best.deadhead_min += dead
    best.blocks.append((eta, done, run["kind"]))

sched = pd.DataFrame(rows)
sched.to_csv(OUT / "schedule.csv", index=False)
(OUT / "audit_log.json").write_text(json.dumps(audit, indent=2))

veh_hours = sum(v.shift_end - v.shift_start for v in FLEET)
stats = {
    "day": DAY, "requests": int(len(day)), "runs": len(runs),
    "served": served, "unserved": unserved,
    "pooled_share": round(sum(len(r["members"]) for r in runs if "pool" in r["kind"]) / len(day), 3),
    "fleet": len(FLEET), "revenue_vehicle_hours": veh_hours,
    "trips_per_revenue_hour": round(served / veh_hours, 2),
    "mean_deadhead_min": round(float(sched.deadhead_min.mean()), 1),
    "deadhead_share_of_drive": round(
        float(sum(v.deadhead_min for v in FLEET) / max(sum(v.drive_min for v in FLEET), 1)), 3),
}
(OUT / "day_stats.json").write_text(json.dumps(stats, indent=2))
print(json.dumps(stats, indent=2))
