/**
 * Drift coverage for `src/generated/openapi.ts`.
 *
 * The generated client went 835 lines stale while two endpoints landed
 * (ADR-0042). The repair was a CI step -- regenerate, then `git diff
 * --exit-code` -- which is byte-exact and correct, and which nothing outside a
 * GitHub runner can run: a developer typing `npm test` gets no signal at all,
 * and the drift is only discovered after it is pushed.
 *
 * These tests are the local half of that gate. They are deliberately WEAKER
 * than the CI check (semantic coverage, not byte equality) and they run in the
 * one place the byte check cannot:
 *
 *   CI       byte-exact, catches formatting and generator-version drift too,
 *            runs on push
 *   here     every path and every schema in the contract is present in the
 *            generated types, runs on `npm test`
 *
 * Neither subsumes the other. This file would have caught the historical
 * failure -- two endpoints in the contract, absent from the types -- on the
 * developer's machine, before the push.
 *
 * The contract JSON is itself generated (`contracts/generate.py`, from
 * `packages/api/app.py`), so the full chain this asserts one link of is:
 *
 *     packages/api/app.py -> contracts/openapi/*.json -> src/generated/openapi.ts
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const CONTRACT = `${here}../../../contracts/openapi/milexium-api-v0.1.json`;
const GENERATED = `${here}../src/generated/openapi.ts`;

interface OpenApiDocument {
  paths: Record<string, Record<string, { operationId?: string }>>;
  components: { schemas: Record<string, unknown> };
}

const contract = JSON.parse(readFileSync(CONTRACT, "utf8")) as OpenApiDocument;
const generated = readFileSync(GENERATED, "utf8");

test("the contract fixture this file reads is the real one, not an empty stub", () => {
  // Guards every assertion below: a contract that parsed to zero paths would
  // make all of them pass over nothing.
  assert.ok(
    Object.keys(contract.paths).length >= 9,
    `expected the full v0.1 endpoint set, found ${Object.keys(contract.paths).length}`,
  );
  assert.ok(Object.keys(contract.components.schemas).length >= 20);
  assert.ok(generated.length > 10_000);
});

test("every path in the OpenAPI contract exists in the generated types", () => {
  const missing = Object.keys(contract.paths).filter(
    (path) => !generated.includes(`"${path}": {`),
  );
  assert.deepEqual(
    missing,
    [],
    `generated types are stale -- run 'npm run generate -w @milexium/sdk'. Missing: ${missing.join(", ")}`,
  );
});

test("every operationId in the contract exists in the generated operations", () => {
  const operationIds: string[] = [];
  for (const methods of Object.values(contract.paths)) {
    for (const operation of Object.values(methods)) {
      if (operation.operationId) operationIds.push(operation.operationId);
    }
  }
  assert.ok(operationIds.length >= 9);
  const missing = operationIds.filter((id) => !generated.includes(`${id}: {`));
  assert.deepEqual(missing, [], `missing operations: ${missing.join(", ")}`);
});

test("every component schema in the contract exists in the generated types", () => {
  // Matched on the DECLARATION (8-space indent inside `components.schemas`)
  // rather than on `Name: {`, because an enum schema is emitted as a union --
  // `DecisionEventType: "recommendation" | ...` -- and a `{`-shaped check
  // silently reported the two enums missing when they were both present.
  const missing = Object.keys(contract.components.schemas).filter(
    (name) => !new RegExp(`^ {8}${name}: `, "m").test(generated),
  );
  assert.deepEqual(missing, [], `missing schemas: ${missing.join(", ")}`);
});

test("the teardown refusal surface survives into the generated types", () => {
  // The point of generating rather than hand-writing: a TypeScript caller must
  // see that these fields do not exist. `TeardownRequest` forbids extras, so a
  // client cannot ask the API to claim a guaranteed saving or causal proof.
  const start = generated.indexOf("TeardownRequest: {");
  assert.ok(start > 0, "TeardownRequest is absent from the generated types");
  const block = generated.slice(start, start + 4000);
  assert.ok(!block.includes("is_guaranteed_saving"));
  assert.ok(!block.includes("causal_proof"));
  assert.ok(block.includes("segments"));
  assert.ok(block.includes("data_provenance"));
});

test("the generated file still says it is generated", () => {
  // If someone hand-edits it, the CI byte check will fight them forever; the
  // banner is the thing that tells them not to start.
  assert.ok(generated.includes("auto-generated by openapi-typescript"));
  assert.ok(generated.includes("Do not make direct changes to the file"));
});
