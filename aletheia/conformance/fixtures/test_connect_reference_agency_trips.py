"""Fixture-level conformance for themis/connect's first adapter slice
(Program B): a trips.csv row maps to a schema-valid ServiceRequest, and
fields the source carries but ServiceRequest v0.1 has no home for are
reported as semantic loss rather than silently discarded (blueprint/
03-connect-and-standards.md, "no adapter leaks vendor-specific meanings
into Core... without recording"). Status: Demonstrated only -- the source
row shape comes from reference_agency's explicitly fictional generator.
"""

from __future__ import annotations

import csv
from pathlib import Path

from themis.canonical import ServiceRequest, ServiceRequestState
from aletheia.verify import verify_against_schema

from conformance.fixtures.builders_connect import example_trip_row, example_trips_adapter

TRIPS_CSV = Path(__file__).parents[3] / "forge" / "business" / "reference_agency" / "output" / "trips.csv"


def test_valid_trip_row_maps_to_a_schema_valid_service_request() -> None:
    adapter, tenant_id = example_trips_adapter()
    result = adapter.parse(example_trip_row())

    assert not result.is_quarantined
    assert result.quarantine is None
    request = result.record
    assert isinstance(request, ServiceRequest)
    assert request.tenant_id == tenant_id
    assert request.status == ServiceRequestState.REQUESTED
    assert request.meta.version == 1
    assert not request.meta.is_correction()
    assert request.pickup_zone == "Z11"
    assert request.dropoff_zone == "Z28"
    assert request.mobility_device is None  # wheelchair="False" in the fixture row
    assert request.rider_ref != "R0022"  # never the raw source id
    assert request.rider_ref.startswith("riderref-")

    errors = verify_against_schema(request.model_dump(mode="json"), ServiceRequest)
    assert errors == []


def test_wheelchair_true_maps_to_mobility_device() -> None:
    adapter, _ = example_trips_adapter()
    result = adapter.parse(example_trip_row(wheelchair="True"))
    assert result.record.mobility_device == "wheelchair"


def test_known_but_uncovered_source_fields_are_recorded_as_semantic_loss() -> None:
    """purpose/subscription/status are real, meaningful trips.csv columns
    that ServiceRequest v0.1 has no field for -- they must be reported, not
    silently dropped on the floor."""

    adapter, _ = example_trips_adapter()
    result = adapter.parse(example_trip_row())

    lost_fields = {loss.source_field: loss for loss in result.semantic_loss}
    assert lost_fields["purpose"].disposition == "dropped"
    assert lost_fields["purpose"].source_value == "dialysis"
    assert lost_fields["subscription"].disposition == "dropped"
    assert lost_fields["status"].disposition == "dropped"
    assert "requested_at" in "".join(
        loss.reason for loss in result.semantic_loss if loss.source_field == "date/hour/req_minute"
    )


def test_extra_vendor_field_is_recorded_as_an_unmapped_extension() -> None:
    """A field entirely outside the documented trips.csv schema (e.g. a
    vendor-specific export adding a column) must surface with disposition
    'unmapped_extension', not vanish or raise."""

    adapter, _ = example_trips_adapter()
    result = adapter.parse(example_trip_row(vendor_dispatch_code="XJ-19"))

    assert not result.is_quarantined
    extension_losses = [loss for loss in result.semantic_loss if loss.disposition == "unmapped_extension"]
    assert len(extension_losses) == 1
    assert extension_losses[0].source_field == "vendor_dispatch_code"
    assert extension_losses[0].source_value == "XJ-19"


def test_adapter_maps_real_generated_trips_csv_without_error() -> None:
    """Runs against the actual forge/business/reference_agency/output/trips.csv already
    generated by forge/business/reference_agency/generate_trips.py in this repo -- not a
    hand-written stand-in for the source shape."""

    if not TRIPS_CSV.exists():
        import pytest

        pytest.skip(f"{TRIPS_CSV} not generated in this environment")

    adapter, _ = example_trips_adapter()
    with TRIPS_CSV.open(newline="") as f:
        rows = list(csv.DictReader(f))[:500]

    results = [adapter.parse(row) for row in rows]
    assert len(results) == 500
    assert all(not r.is_quarantined for r in results)
